# Create tuples
MyTuple1 = () # Empty tuple
MyTuple2 = (50,) # Single value tuple =
MyTuple3 = (10, 20, 30, 40)
MyTuple4= (2017, 'python' , "Cut-off", 50.00) 

# Display Tuples
print (MyTuple1)
print (MyTuple2)
print (MyTuple3)
print (MyTuple4)

# Display specific values (using slicer)
print (MyTuple2 [0])
print (MyTuple3 [2])
print (MyTuple4 [1:3])